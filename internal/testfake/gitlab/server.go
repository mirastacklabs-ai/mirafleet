// Event is one authentication attempt seen by the fake. Credential is what the client presented
// (SSH key fingerprint, HTTPS token or registry password/bearer): the fake is a test double and
// keeps it so tests can assert which credential reached it.
type Event struct {
	Transport  string // ssh, https, registry-basic, registry-bearer
	Identity   string // user name presented
	Credential string
	OK         bool
}

// DeployKey is a generated ed25519 SSH key pair.
type DeployKey struct {
	PrivatePEM  []byte // OpenSSH format, for ssh -i or the credential store
	Public      ssh.PublicKey
	Authorized  string // authorized_keys line
	Fingerprint string // SHA256:...
}

// NewDeployKey generates a deploy key.
func NewDeployKey(t testing.TB) *DeployKey {
	t.Helper()
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	blk, err := ssh.MarshalPrivateKey(priv, "deploy")
	if err != nil {
		t.Fatal(err)
	}
	sp, err := ssh.NewPublicKey(pub)
	if err != nil {
		t.Fatal(err)
	}
	return &DeployKey{
		PrivatePEM:  pem.EncodeToMemory(blk),
		Public:      sp,
		Authorized:  strings.TrimSpace(string(ssh.MarshalAuthorizedKey(sp))),
		Fingerprint: ssh.FingerprintSHA256(sp),
	}
}

// Options configures Start. Zero values pick ephemeral loopback ports.
type Options struct {
	Root         string   // git project root; default t.TempDir()
	HTTPSAddr    string   // git (and registry unless RegistryAddr is set); default 127.0.0.1:0
	SSHAddr      string   // default 127.0.0.1:0
	RegistryAddr string   // optional separate registry listener (registry.gitlab.test style)
	Hosts        []string // certificate names/IPs; default gitlab.test, registry.gitlab.test, localhost, 127.0.0.1
	CA           *CA      // default: a new one
}

// Server is the fake GitLab. The accepted credentials are generated by Start.
type Server struct {
	CA               *CA
	Root             string
	DeployKey        *DeployKey
	ProjectToken     string // accepted as the HTTPS password (any user name)
	RegistryUser     string
	RegistryPassword string

	HTTPSAddr, SSHAddr, RegistryAddr string // bound addresses (host:port)

	hostKey ssh.Signer
	backend string

	mu     sync.Mutex
	events []Event
	tokens map[string]string // issued bearer token -> scope
	blobs  map[string][]byte // digest -> bytes
	mfs    map[string]image  // "name:ref" -> manifest
}

func randHex(t testing.TB, n int) string {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		t.Fatal(err)
	}
	return hex.EncodeToString(b)
}

// Start brings the fake up and registers cleanup with t.
func Start(t testing.TB, o Options) *Server {
	t.Helper()
	if o.Root == "" {
		o.Root = t.TempDir()
	}
	if o.HTTPSAddr == "" {
		o.HTTPSAddr = "127.0.0.1:0"
	}
	if o.SSHAddr == "" {
		o.SSHAddr = "127.0.0.1:0"
	}
	if len(o.Hosts) == 0 {
		o.Hosts = []string{"gitlab.test", "registry.gitlab.test", "localhost", "127.0.0.1"}
	}
	if o.CA == nil {
		o.CA = NewCA(t)
	}
	out, err := exec.Command("git", "--exec-path").Output()
	if err != nil {
		t.Fatalf("git not available: %v", err)
	}
	_, hk, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	signer, err := ssh.NewSignerFromKey(hk)
	if err != nil {
		t.Fatal(err)
	}
	s := &Server{
		CA: o.CA, Root: o.Root, DeployKey: NewDeployKey(t),
		ProjectToken: "glpat-" + randHex(t, 16),
		RegistryUser: "reg-" + randHex(t, 4), RegistryPassword: randHex(t, 16),
		hostKey: signer,
		backend: filepath.Join(strings.TrimSpace(string(out)), "git-http-backend"),
		tokens:  map[string]string{}, blobs: map[string][]byte{}, mfs: map[string]image{},
	}
	cert := o.CA.Issue(t, o.Hosts...)
	tlsCfg := &tls.Config{Certificates: []tls.Certificate{cert}, MinVersion: tls.VersionTLS12}

	listen := func(addr string) net.Listener {
		l, err := net.Listen("tcp", addr)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { l.Close() })
		return l
	}
	serveHTTPS := func(l net.Listener, h http.Handler) {
		srv := &http.Server{Handler: h}
		go srv.Serve(tls.NewListener(l, tlsCfg))
		t.Cleanup(func() { srv.Close() })
	}

	mux := http.NewServeMux()
	reg := http.HandlerFunc(s.registry)
	if o.RegistryAddr == "" {
		mux.Handle("/v2/", reg)
		mux.HandleFunc("/jwt/auth", s.tokenEndpoint)
	}
	mux.HandleFunc("/", s.gitHTTP)
	l := listen(o.HTTPSAddr)
	s.HTTPSAddr = l.Addr().String()
	serveHTTPS(l, mux)

	if o.RegistryAddr != "" {
		rm := http.NewServeMux()
		rm.Handle("/v2/", reg)
		rm.HandleFunc("/jwt/auth", s.tokenEndpoint)
		rl := listen(o.RegistryAddr)
		s.RegistryAddr = rl.Addr().String()
		serveHTTPS(rl, rm)
	} else {
		s.RegistryAddr = s.HTTPSAddr
	}

	sl := listen(o.SSHAddr)
	s.SSHAddr = sl.Addr().String()
	go s.serveSSH(sl)
	return s
}

// KnownHostsLine is the known_hosts entry (host may be "[gitlab.test]:2222") for the SSH host key.
func (s *Server) KnownHostsLine(host string) string {
	return host + " " + strings.TrimSpace(string(ssh.MarshalAuthorizedKey(s.hostKey.PublicKey())))
}

// HostKeyFingerprint is the SHA256 fingerprint of the SSH host key.
func (s *Server) HostKeyFingerprint() string { return ssh.FingerprintSHA256(s.hostKey.PublicKey()) }

// Events returns a copy of every authentication attempt so far.
func (s *Server) Events() []Event {
	s.mu.Lock()
	defer s.mu.Unlock()
	return append([]Event(nil), s.events...)
}

func (s *Server) record(e Event) {
	s.mu.Lock()
	s.events = append(s.events, e)
	s.mu.Unlock()
}

func eq(a, b string) bool { return subtle.ConstantTimeCompare([]byte(a), []byte(b)) == 1 }

// gitHTTP is git smart-HTTP behind HTTP basic auth: any user name, the project token as password.
func (s *Server) gitHTTP(w http.ResponseWriter, r *http.Request) {
	user, pass, ok := r.BasicAuth()
	good := ok && eq(pass, s.ProjectToken)
	if ok {
		s.record(Event{Transport: "https", Identity: user, Credential: pass, OK: good})
	}
	if !good {
		w.Header().Set("WWW-Authenticate", `Basic realm="GitLab"`)
		http.Error(w, "401 Unauthorized", http.StatusUnauthorized)
		return
	}
	if strings.Contains(r.URL.Path, "..") {
		http.Error(w, "bad path", http.StatusBadRequest)
		return
	}
	(&cgi.Handler{
		Path: s.backend, Dir: s.Root, InheritEnv: []string{"PATH", "HOME"},
		Env: []string{
			"GIT_PROJECT_ROOT=" + s.Root, "GIT_HTTP_EXPORT_ALL=1", "REMOTE_USER=" + user,
			"GIT_CONFIG_COUNT=1", "GIT_CONFIG_KEY_0=http.receivepack", "GIT_CONFIG_VALUE_0=true",
		},
	}).ServeHTTP(w, r)
}
