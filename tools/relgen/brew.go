package main

import (
	"bufio"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// brewRepo is the GitHub repository the release archives are served from.
const brewRepo = "https://github.com/mirastacklabs-ai/mirafleet"

// brewPlatform is one archive the formula points at. The archive name follows the goreleaser
// default name_template: mirafleet_<version>_<os>_<arch>.tar.gz.
type brewPlatform struct{ OS, Arch string }

// brewPlatforms is the fixed set, in the order the formula lists them.
var brewPlatforms = []brewPlatform{
	{"darwin", "arm64"}, {"darwin", "amd64"}, {"linux", "arm64"}, {"linux", "amd64"},
}

func brewArchive(version string, p brewPlatform) string {
	return fmt.Sprintf("mirafleet_%s_%s_%s.tar.gz", version, p.OS, p.Arch)
}

func init() {
	register(command{
		Name: "brew", Usage: "[-checksums F] [-dist DIR] [-out F] vX.Y.Z",
		Summary: "render the Homebrew formula from checksums.txt",
		Run:     runBrew,
	})
}

var brewSumLineRE = regexp.MustCompile(`^([0-9a-f]{64}) [ *](\S+)$`)

// parseChecksums reads a sha256sum-style file into name -> hex digest.
func parseChecksums(r io.Reader) (map[string]string, error) {
	sums := map[string]string{}
	sc := bufio.NewScanner(r)
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimRight(sc.Text(), " \t\r")
		if line == "" {
			continue
		}
		m := brewSumLineRE.FindStringSubmatch(line)
		if m == nil {
			return nil, fmt.Errorf("checksums line %d: not '<sha256>  <name>'", n)
		}
		if _, dup := sums[m[2]]; dup {
			return nil, fmt.Errorf("checksums line %d: %s listed twice", n, m[2])
		}
		sums[m[2]] = m[1]
	}
	return sums, sc.Err()
}

// brewVerifyDist hashes each archive found in dir and compares it with the checksums file. An
// archive that is missing from dir is an error: the formula must never point at an unchecked file.
func brewVerifyDist(dir string, names []string, sums map[string]string) error {
	for _, name := range names {
		f, err := os.Open(filepath.Join(dir, name)) // name comes from brewArchive, never from input
		if err != nil {
			return err
		}
		h := sha256.New()
		_, err = io.Copy(h, f)
		f.Close()
		if err != nil {
			return err
		}
		if got := hex.EncodeToString(h.Sum(nil)); got != sums[name] {
			return fmt.Errorf("%s: sha256 %s does not match checksums.txt (%s)", name, got, sums[name])
		}
	}
	return nil
}

// renderBrew builds the formula text for a release version (no leading v).
func renderBrew(version string, sums map[string]string) (string, error) {
	sha := func(p brewPlatform) (string, error) {
		name := brewArchive(version, p)
		s, ok := sums[name]
		if !ok {
			return "", fmt.Errorf("checksums.txt has no entry for %s", name)
		}
		return s, nil
	}
	var b strings.Builder
	b.WriteString("# Generated by `relgen brew` from the release checksums.txt. Do not edit by hand.\n")
	b.WriteString("class Mirafleet < Formula\n")
	b.WriteString("  desc \"Claude Code orchestrates fleets of servers through a central server\"\n")
	b.WriteString("  homepage \"" + brewRepo + "\"\n")
	b.WriteString("  version \"" + version + "\"\n")
	b.WriteString("  license \"Apache-2.0\"\n")
	for _, osName := range []string{"macos", "linux"} {
		goos := map[string]string{"macos": "darwin", "linux": "linux"}[osName]
		b.WriteString("\n  on_" + osName + " do\n")
		for _, cpu := range []struct{ blk, arch string }{{"on_arm", "arm64"}, {"on_intel", "amd64"}} {
			p := brewPlatform{goos, cpu.arch}
			s, err := sha(p)
			if err != nil {
				return "", err
			}
			b.WriteString("    " + cpu.blk + " do\n")
			b.WriteString("      url \"" + brewRepo + "/releases/download/v" + version + "/" + brewArchive(version, p) + "\"\n")
			b.WriteString("      sha256 \"" + s + "\"\n")
			b.WriteString("    end\n")
		}
		b.WriteString("  end\n")
	}
	b.WriteString("\n  def install\n    bin.install \"mirafleet\"\n  end\n")
	b.WriteString("\n  test do\n    assert_match version.to_s, shell_output(\"#{bin}/mirafleet version\")\n  end\nend\n")
	return b.String(), nil
}

func runBrew(e env, args []string) error {
	fs := flag.NewFlagSet("brew", flag.ContinueOnError)
	fs.SetOutput(e.Err)
	sumsPath := fs.String("checksums", "", "checksums.txt (default dist/checksums.txt under the root)")
	dist := fs.String("dist", "", "directory with the archives; when set, each is hashed and compared")
	out := fs.String("out", "", "write the formula here instead of stdout")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if fs.NArg() != 1 {
		return errors.New("usage: relgen brew [-checksums F] [-dist DIR] [-out F] vX.Y.Z")
	}
	version, err := parseTag(fs.Arg(0))
	if err != nil {
		return err
	}
	if strings.Contains(version, "-") {
		return fmt.Errorf("v%s is a pre-release; the tap only carries final releases", version)
	}
	if *sumsPath == "" {
		*sumsPath = filepath.Join(e.Root, "dist", "checksums.txt")
	}
	f, err := os.Open(*sumsPath)
	if err != nil {
		return err
	}
	sums, err := parseChecksums(f)
	f.Close()
	if err != nil {
		return err
	}
	text, err := renderBrew(version, sums)
	if err != nil {
		return err
	}
	if *dist != "" {
		names := make([]string, len(brewPlatforms))
		for i, p := range brewPlatforms {
			names[i] = brewArchive(version, p)
		}
		if err := brewVerifyDist(*dist, names, sums); err != nil {
			return err
		}
	}
	if *out == "" {
		_, err = io.WriteString(e.Out, text)
		return err
	}
	return os.WriteFile(*out, []byte(text), 0o644)
}
